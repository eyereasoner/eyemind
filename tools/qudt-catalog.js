#!/usr/bin/env node
// Write src/qudt-catalog.js, the offline QUDT unit catalog of --qudt, from a
// release of the QUDT unit vocabulary (CC BY 4.0). npm run sync fetches the
// latest release; a local copy can be given directly:
//
//     node tools/qudt-catalog.js VOCAB_QUDT-UNITS-ALL.ttl v3.5.3
//
// The file is in the release's src/main/rdf/vocab/unit/ directory of
// https://github.com/qudt/qudt-public-repo. Each unit that is not deprecated
// and has a nonzero multiplier and a dimension vector keeps its multiplier,
// offset, dimension vector, UCUM codes and quantity kinds, and whether it is a
// coherent SI unit; currencies and units without a fixed conversion are left
// out.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseRdf } from '../src/rdf.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const QUDT_SOURCE = 'https://github.com/qudt/qudt-public-repo';
export const QUDT_UNITS = 'src/main/rdf/vocab/unit/VOCAB_QUDT-UNITS-ALL.ttl';

// Write the catalog of the unit vocabulary in file, of this release and
// revision; returns the number of units.
export function writeQudtCatalog(file, release, { root = ROOT, revision = null } = {}) {
const Q = 'http://qudt.org/schema/qudt/', U = 'http://qudt.org/vocab/unit/', D = 'http://qudt.org/vocab/dimensionvector/';
const SI = 'http://qudt.org/vocab/sou/SI', K = 'http://qudt.org/vocab/quantitykind/';
const { quads } = parseRdf(readFileSync(file, 'utf8'), { format: 'turtle' });
const about = new Map();
for (const [s, p, o] of quads) {
  if (s?.name !== 'iri' || !s.args[0].startsWith(U)) continue;
  const name = s.args[0].slice(U.length);
  if (!about.has(name)) about.set(name, new Map());
  const values = about.get(name);
  const property = p.args[0].startsWith(Q) ? p.args[0].slice(Q.length) : p.args[0];
  if (!values.has(property)) values.set(property, []);
  values.get(property).push(o);
}
// The lexical form of a number as QUDT states it, so no digit is lost.
const lexical = (term) => term === undefined ? null : typeof term === 'bigint' ? String(term)
  : term.name === 'literal' ? term.args[0] : null;
const dimensions = [], kindNames = [];
const lines = [];
for (const [name, values] of [...about].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
  const one = (property) => values.get(property)?.[0];
  if (lexical(one('deprecated')) === 'true') continue;
  // A currency has no fixed conversion, though QUDT gives it multiplier 1.
  const kinds = [...(values.get('hasQuantityKind') ?? []), ...(values.get('unitForQuantityKind') ?? [])].map((o) => o.args?.[0] ?? '');
  const types = (values.get('http://www.w3.org/1999/02/22-rdf-syntax-ns#type') ?? []).map((o) => o.args?.[0] ?? '');
  // So has a unit made of one, as CCY_EUR-PER-KiloW-HR: normalizing it
  // would lose the currency.
  if (/(^|-)CCY_/.test(name) || kinds.some((k) => k.startsWith('http://qudt.org/vocab/quantitykind/Currency')) ||
      types.some((t) => /CurrencyUnit$/.test(t))) continue;
  const multiplier = lexical(one('conversionMultiplier'));
  const dimension = one('hasDimensionVector')?.args?.[0]?.slice(D.length);
  if (multiplier === null || Number(multiplier) === 0 || !Number.isFinite(Number(multiplier)) || !dimension) continue;
  const offset = lexical(one('conversionOffset')) ?? '0';
  if (!Number.isFinite(Number(offset))) continue;
  let index = dimensions.indexOf(dimension);
  if (index < 0) index = dimensions.push(dimension) - 1;
  const codes = (values.get('ucumCode') ?? []).map(lexical).filter((code) => code && !/\s/.test(code));
  const coherent = (values.get('derivedCoherentUnitOfSystem') ?? []).some((o) => o.args?.[0] === SI) && Number(multiplier) === 1 &&
    Number(offset) === 0 ? 1 : 0;
  // Its quantity kinds, as indexes into KINDS.
  const kindIndexes = [...new Set(kinds.filter((k) => k.startsWith(K)).map((k) => k.slice(K.length)))].sort().map((k) => {
    const i = kindNames.indexOf(k);
    return i < 0 ? kindNames.push(k) - 1 : i;
  });
  lines.push([name, Number(multiplier), Number(offset), index, coherent, codes.join(' '), kindIndexes.join(' ')].join('\t'));
}
const text = `// Generated by tools/qudt-catalog.js from the QUDT unit vocabulary ${release}${revision ? ` (${revision})` : ''},
// ${QUDT_SOURCE} (CC BY 4.0). Do not edit by hand.
// Each line: unit, multiplier, offset, dimension vector index, whether it is
// a coherent SI unit, its UCUM codes, and its quantity kinds by index.
export const QUDT_RELEASE = ${JSON.stringify(release)};
export const DIMENSIONS = ${JSON.stringify(dimensions)};
export const KINDS = ${JSON.stringify(kindNames)};
export const UNITS = ${JSON.stringify(lines.join('\n'))};
`;
writeFileSync(join(root, 'src/qudt-catalog.js'), text);
return { units: lines.length, dimensions: dimensions.length, kinds: kindNames.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [file, release] = process.argv.slice(2);
  if (!file || !release) {
    console.error('usage: node tools/qudt-catalog.js VOCAB_QUDT-UNITS-ALL.ttl RELEASE');
    process.exit(1);
  }
  const { units, dimensions } = writeQudtCatalog(file, release);
  console.log(`wrote src/qudt-catalog.js: ${units} units, ${dimensions} dimension vectors`);
}
