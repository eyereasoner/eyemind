// A bounded ODRL snapshot profile: one Turtle document supplies the policies,
// candidate requests and their state of the world. Both validation and
// evaluation are ordinary LS, included in the standalone compiled program.
// ODRL semantics: https://www.w3.org/TR/odrl-model/
import { EyemindError, Struct } from './terms.js';
import { DEFAULT_GRAPH } from './rdf.js';
import { loadText } from './lang.js';
import { write } from './writer.js';

export const ODRL_EVAL = 'https://eyereasoner.github.io/eyemind/odrl#';
const RDF = 'http://www.w3.org/1999/02/22-rdf-syntax-ns#';

export function isOdrlEvaluation(quads) {
  return quads.some(([, predicate, object]) => predicate instanceof Struct && predicate.name === 'iri' &&
    predicate.args[0] === `${RDF}type` && object instanceof Struct && object.name === 'iri' &&
    object.args[0] === `${ODRL_EVAL}Evaluation`);
}

export function compileOdrl({ quads, prefixes }, { source = '<input>' } = {}) {
  if (!isOdrlEvaluation(quads)) throw new EyemindError('--odrl needs an eval:Evaluation resource selecting the policies and requests');
  if (quads.some(([, , , graph]) => graph !== DEFAULT_GRAPH)) throw new EyemindError('an ODRL snapshot needs one default graph');
  // RDF graphs are sets; repeated statements must not violate cardinalities.
  const facts = [...new Set(quads.map(([s, p, o]) => write(new Struct('odrl_input', [s, p, o]))))].join('\n');
  const text = `// Generated by eyemind from ${String(source).replace(/[\r\n\u2028\u2029]/g, ' ')}, an ODRL snapshot.\n` +
    '// Input triples are odrl_input(S, P, O); report triples are rdf(S, P, O).\n' +
    `facts_from({ text: ${JSON.stringify(facts)} })\n${RULES}`;
  return { kind: 'odrl', text, program: loadText(text, source), prefixes: { ...prefixes, eval: ODRL_EVAL }, compiled: null };
}

