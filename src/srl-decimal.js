// Exact decimal values as decimal(Coefficient, Scale), meaning C / 10^S.
// These are ordinary rules: the proof checker re-decides their integer
// arithmetic without a decimal implementation or calls to the reasoner.
export const decimalRules = String.raw`
implied_by(srl_decimal_text(L, decimal(C, S)), [regex_find('^[ \\t\\n\\r]*([+-]?)([0-9]*)(?:\\.([0-9]*))?[ \\t\\n\\r]*$', L, [_, Sign, I, F]), atom_concat(I, F, Ds), atom_length(Ds, N), gt(N, 0), atom_chars(Ds, Cs), number_chars(A, Cs), atom_length(F, S), srl_decimal_sign(Sign, A, C)])
implied_by(srl_decimal_sign('', A, A), 'true')
implied_by(srl_decimal_sign('+', A, A), 'true')
implied_by(srl_decimal_sign('-', A, C), is(C, neg(A)))
implied_by(srl_decimal_normal(decimal(C, S), decimal(N, T)), once(srl_decimal_normal_(C, S, N, T)))
implied_by(srl_decimal_normal_(0, _, 0, 0), 'true')
implied_by(srl_decimal_normal_(C, S, N, T), [ne(C, 0), gt(S, 0), eq(mod(C, 10), 0), is(A, floordiv(C, 10)), is(B, sub(S, 1)), srl_decimal_normal_(A, B, N, T)])
implied_by(srl_decimal_normal_(C, S, C, S), or(eq(S, 0), ne(mod(C, 10), 0)))
implied_by(srl_decimal_lexical(V, L), [srl_decimal_normal(V, decimal(C, S)), is(A, abs(C)), number_chars(A, Cs), atom_chars(Ds, Cs), atom_length(Ds, N), is(P, sub(N, S)), srl_point(Ds, N, P, B), srl_decimal_prefix(C, Sign), atom_concat(Sign, B, L)])
implied_by(srl_decimal_prefix(C, '-'), lt(C, 0))
implied_by(srl_decimal_prefix(C, ''), ge(C, 0))
implied_by(srl_decimal_value(N, decimal(N, 0)), is_int(N))
implied_by(srl_decimal_value(decimal(C, S), decimal(C, S)), 'true')
implied_by(srl_decimal_value(F, D), [is_float(F), number_chars(F, Cs), atom_chars(A, Cs), srl_float_text('decimal', A, L), srl_decimal_text(L, D)])
implied_by(srl_float_value(N, F), [srl_float_operand(N), float64('convert', N, 0, F)])
implied_by(srl_float_operand(N), is_number(N))
implied_by(srl_float_operand(N), srl_float_special(N))
fact(srl_float_special('INF'), srl_float_special('-INF'), srl_float_special('NaN'))
implied_by(srl_float_lexical(N, L), [is_float(N), number_chars(N, Cs), atom_chars(L, Cs)])
implied_by(srl_float_lexical(N, N), srl_float_special(N))
implied_by(srl_float_value(D, F), [unify(D, decimal(_, _)), srl_decimal_lexical(D, L), float64('parse', L, 0, F)])
implied_by(srl_numeric_value('integer', N, N), is_int(N))
implied_by(srl_numeric_value('decimal', V, D), srl_decimal_value(V, D))
implied_by(srl_numeric_value(K, V, F), [srl_float_kind(K), srl_float_value(V, F)])
implied_by(srl_pair(A, B, K, X, Y), [srl_num(A, KA, VA), srl_num(B, KB, VB), srl_promote(KA, KB, K), srl_numeric_value(K, VA, X), srl_numeric_value(K, VB, Y)])
implied_by(srl_decimal_align(decimal(A, S), decimal(B, T), X, Y, U), [is(U, max(S, T)), is(X, mul(A, pow(10, sub(U, S)))), is(Y, mul(B, pow(10, sub(U, T))))])
implied_by(srl_calculate('add', decimal(A, S), decimal(B, T), decimal(C, U)), [srl_decimal_align(decimal(A, S), decimal(B, T), X, Y, U), is(C, add(X, Y))])
implied_by(srl_calculate('sub', decimal(A, S), decimal(B, T), decimal(C, U)), [srl_decimal_align(decimal(A, S), decimal(B, T), X, Y, U), is(C, sub(X, Y))])
implied_by(srl_calculate('mul', decimal(A, S), decimal(B, T), decimal(C, U)), [is(C, mul(A, B)), is(U, add(S, T))])
// Reduce a quotient first. Terminating division is exact; otherwise keep
// at least 34 significant digits, rounded to nearest with ties to even.
implied_by(srl_calculate('div', decimal(A, S), decimal(B, T), decimal(C, U)), [ne(B, 0), is(N, mul(A, pow(10, T))), is(D, mul(B, pow(10, S))), is(G, gcd(N, D)), is(P, floordiv(abs(N), G)), is(Q, floordiv(abs(D), G)), srl_decimal_places(Q, P, U), is(Z, mul(P, pow(10, U))), is(H, floordiv(Z, Q)), is(R, mod(Z, Q)), srl_decimal_round(H, R, Q, V), srl_decimal_quotient_sign(N, D, V, C)])
implied_by(srl_decimal_places(Q, P, U), [srl_decimal_factors(Q, 2, 0, A, I), srl_decimal_factors(A, 5, 0, B, J), srl_decimal_precision(B, P, Q, I, J, U)])
implied_by(srl_decimal_factors(N, D, I, R, K), once(srl_decimal_factors_(N, D, I, R, K)))
implied_by(srl_decimal_factors_(N, D, I, R, K), [eq(mod(N, D), 0), is(M, floordiv(N, D)), is(J, add(I, 1)), srl_decimal_factors_(M, D, J, R, K)])
implied_by(srl_decimal_factors_(N, D, I, N, I), ne(mod(N, D), 0))
implied_by(srl_decimal_precision(1, _, _, I, J, U), is(U, max(I, J)))
implied_by(srl_decimal_precision(B, P, Q, _, _, U), [ne(B, 1), number_chars(P, Ps), number_chars(Q, Qs), srl_length(Ps, NP), srl_length(Qs, NQ), is(U, max(0, add(34, sub(NQ, NP))))])
implied_by(srl_decimal_round(H, R, Q, V), [is(D, sub(mul(R, 2), Q)), srl_decimal_round_(D, H, V)])
implied_by(srl_decimal_round_(D, H, H), lt(D, 0))
implied_by(srl_decimal_round_(D, H, V), [gt(D, 0), is(V, add(H, 1))])
implied_by(srl_decimal_round_(0, H, V), is(V, add(H, mod(H, 2))))
implied_by(srl_decimal_quotient_sign(N, D, V, C), [lt(mul(N, D), 0), is(C, neg(V))])
implied_by(srl_decimal_quotient_sign(N, D, V, V), ge(mul(N, D), 0))
implied_by(srl_value_compare(decimal(A, S), decimal(B, T), O), [srl_decimal_align(decimal(A, S), decimal(B, T), X, Y, _), srl_compare(X, Y, O)])
implied_by(srl_value_compare(X, Y, O), [is_int(X), is_int(Y), srl_compare(X, Y, O)])
implied_by(srl_value_compare(X, Y, O), [srl_float_operand(X), srl_float_operand(Y), not(and(is_int(X), is_int(Y))), float64('compare', X, Y, O)])
implied_by(srl_value_zero(decimal(C, _), C), 'true')
implied_by(srl_value_zero(N, N), is_number(N))
fact(srl_value_zero('NaN', 0), srl_value_zero('INF', 1), srl_value_zero('-INF', 1))
implied_by(srl_unary('neg', decimal(C, S), decimal(N, S)), is(N, neg(C)))
implied_by(srl_unary('abs', decimal(C, S), decimal(N, S)), is(N, abs(C)))
implied_by(srl_unary('floor', decimal(C, S), N), is(N, floordiv(C, pow(10, S))))
implied_by(srl_unary('ceil', decimal(C, S), N), is(N, neg(floordiv(neg(C), pow(10, S)))))
implied_by(srl_unary('trunc', decimal(C, S), N), [is(A, floordiv(abs(C), pow(10, S))), srl_decimal_quotient_sign(C, 1, A, N)])
implied_by(srl_unary('round', decimal(C, S), N), [is(D, pow(10, S)), is(N, floordiv(add(mul(C, 2), D), mul(D, 2)))])
${['neg', 'abs', 'floor', 'ceil', 'trunc'].map((op) => `implied_by(srl_unary('${op}', X, V), [is_int(X), is(V, ${op}(X))])`).join('\n')}
implied_by(srl_unary('round', X, X), is_int(X))
implied_by(srl_unary(Op, X, V), [srl_float_operand(X), not(is_int(X)), float64(Op, X, 0, V)])
${['add', 'sub', 'mul'].map((op) => `implied_by(srl_calculate('${op}', X, Y, V), [is_int(X), is_int(Y), is(V, ${op}(X, Y))])`).join('\n')}
implied_by(srl_calculate(Op, X, Y, V), [srl_float_operand(X), srl_float_operand(Y), not(and(is_int(X), is_int(Y))), float64(Op, X, Y, V)])
`;
