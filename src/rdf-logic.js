// wanted: rdf/4 patterns of the output contract, or null for every new triple.
export function compileRdfLogic({ quads, prefixes, shapes = quads, wanted = null }, {
  profiles, source = '<input>', disallows, evaluate, context, stream = false, stableRuleIds = false,
}) {
  quads = [...new Map(quads.map((q) => [q.map((t) => write(t)).join(' '), q])).values()];
  const selected = new Set(profiles), needs = new Set();
  // SHACL node expressions may call SPARQL functions beyond the value rules.
  const shacl = selected.has('shacl') ? compileShacl(shapes, { disallows, needs, evaluate }) : '';
  const own = [...needs].filter((n) => NODE_FUNCTIONS[n]);
  const execution = ['srl_now', 'srl_uuid', 'sh_ne_rand'].some((n) => needs.has(n)) ? executionContext(context ?? null) : null;
  const data = `facts_from({ text: ${JSON.stringify(rdfDocument(quads))} })\n` +
    `facts_from({ text: ${JSON.stringify(rdfDocument(quads, 'ent_base'))} })\n`;
  const defaultGraph = quads.length ? '' : "fact(ent_graph('default_graph'));\n";
  // In a recompiled stream, the background's witnesses must keep the same
  // clause numbers after a message adds RDF and catalog facts.
  const text = `// Generated by eyemind from ${String(source).replace(/[\r\n\u2028\u2029]/g, ' ')}, with ${profiles.map((p) => '--' + p).join(' ')}.\n` +
    '// rdf(S, P, O, G) is the working graph; result_rdf contains conclusions and reports.\n' +
    (stableRuleIds ? '' : data) + COMMON + (stableRuleIds ? '' : defaultGraph) +
    (profiles.some((p) => p !== 'skos') ? rdfValueRules([...needs].filter((n) => !NODE_FUNCTIONS[n])) : '') +
    own.map((n) => NODE_FUNCTIONS[n] + '\n').join('') +
    (execution ? `implied_by(srl_execution(${JSON.stringify(execution.now)}, ${JSON.stringify(execution.seed)}), 'true');\n` : '') +
    (selected.has('owl2rl') ? owl2rlRules : '') +
    (selected.has('skos') ? skosRules : '') +
    (selected.has('qudt') ? qudtRules(stableRuleIds ? [] : quads) : '') +
    shacl + (evaluate ? "query(sh_evaluation(R));\n" : REPORTS + (stream ? '' : wanted === null ? RESULT : contracted(wanted))) +
    (stableRuleIds ? data + defaultGraph + (selected.has('qudt') ? qudtUnits(quads) : '') : '');
  return { kind: profiles[0], text, program: loadText(text, source),
    prefixes: { ...prefixes, ent: ENTAILMENT, ...(selected.has('skos') ? { skos: 'http://www.w3.org/2004/02/skos/core#' } : {}),
      ...(selected.has('qudt') ? { qconv: 'https://eyereasoner.github.io/eyemind/qudt#', qudt: 'http://qudt.org/schema/qudt/', unit: 'http://qudt.org/vocab/unit/' } : {}),
      ...(selected.has('shacl') ? { sh: 'http://www.w3.org/ns/shacl#' } : {}) }, compiled: null };
}

const SH = 'http://www.w3.org/ns/shacl#';
const RDF = 'http://www.w3.org/1999/02/22-rdf-syntax-ns#';
const XSD_INTEGER = 'http://www.w3.org/2001/XMLSchema#integer';
const TARGETS = ['targetClass', 'targetNode', 'targetSubjectsOf', 'targetObjectsOf'];

// SHACL shapes read as contracts, not validated: the triple patterns their
// property shapes describe. A value is an instance of what one of its
// constraints allows (sh:hasValue, sh:in, sh:datatype, sh:nodeKind or
// sh:class), or anything. A path that is not a predicate or an inverse
// predicate describes triples of each predicate in it, of any value.
function shapePatterns(quads, name, input) {
  const about = new Map();
  for (const quad of quads) {
    const id = identity(quad[0]);
    if (!about.has(id)) about.set(id, []);
    about.get(id).push(quad);
  }
  const values = (node, property) => (about.get(identity(node)) ?? [])
    .filter((q) => q[1].args[0] === property).map((q) => q[2]);
  const value = (node, property) => values(node, property)[0];
  const list = (node) => {
    const items = [];
    for (let at = node, seen = new Set(); at && !(at.name === 'iri' && at.args[0] === RDF + 'nil') && !seen.has(identity(at)); at = value(at, RDF + 'rest')) {
      seen.add(identity(at));
      items.push(value(at, RDF + 'first'));
    }
    return items.filter(Boolean);
  };
  const named = (term) => term?.name === 'iri' ? term.args[0] : null;
  const any = () => new Var(`S#${++fresh}`);
  // The terms a value of this shape is an instance of.
  const valueTerms = (node, kept) => {
    const given = [...values(node, SH + 'hasValue'), ...values(node, SH + 'in').flatMap(list)];
    if (given.length) return given.map((term) => kept ? term : shape(term));
    const datatype = named(value(node, SH + 'datatype'));
    if (datatype === XSD_INTEGER) return [any()];
    if (datatype === RDF + 'langString') return [new Struct('literal', [any(), new Struct('lang', [any()])])];
    if (datatype) return [new Struct('literal', [any(), new Struct('datatype', [datatype])])];
    const kind = named(value(node, SH + 'nodeKind'))?.slice(SH.length);
    const iri = () => new Struct('iri', [any()]), bnode = () => new Struct('bnode', [any(), any()]);
    if (kind === 'IRI') return [iri()];
    if (kind === 'BlankNode') return [bnode()];
    if (kind === 'BlankNodeOrIRI' || (!kind && values(node, SH + 'class').length)) return [iri(), bnode()];
    // A message literal is a literal term; an integer, which is a number
    // term, then does not conform. An output contract asks for any literal.
    const literal = () => input ? new Struct('literal', [any(), any()]) : any();
    if (kind === 'Literal') return [literal()];
    if (kind === 'IRIOrLiteral') return [iri(), literal()];
    if (kind === 'BlankNodeOrLiteral') return [bnode(), literal()];
    return [any()];
  };
  // The predicates of a path, and whether it is a predicate or its inverse.
  const path = (node) => {
    if (named(node)) return { predicates: [named(node)], direct: true };
    const inverse = value(node, SH + 'inversePath');
    if (named(inverse)) return { predicates: [named(inverse)], inverse: true };
    const parts = [inverse, ...values(node, SH + 'alternativePath').flatMap(list),
      ...['zeroOrMorePath', 'oneOrMorePath', 'zeroOrOnePath'].map((p) => value(node, SH + p)), ...list(node)].filter(Boolean);
    if (!parts.length) throw new EyemindError(`${name}: a SHACL path is a predicate, a list or one of the sh: path forms`);
    return { predicates: parts.flatMap((part) => path(part).predicates) };
  };
  const owners = new Map();
  for (const quad of quads) {
    if (quad[1].args[0] === SH + 'property') owners.set(identity(quad[2]), [...(owners.get(identity(quad[2])) ?? []), quad[0]]);
  }
  const patterns = [], allowed = new Set();
  const isTrue = (term) => term?.name === 'literal' && term.args[0] === 'true';
  const nodeShapes = [...about.values()].map((stated) => stated[0][0]).filter((node) => values(node, SH + 'property').length ||
    values(node, RDF + 'type').some((t) => named(t) === SH + 'NodeShape') || TARGETS.some((t) => values(node, SH + t).length));
  const closed = nodeShapes.length > 0 && nodeShapes.every((node) => values(node, SH + 'closed').some(isTrue));
  for (const node of nodeShapes) for (const p of values(node, SH + 'ignoredProperties').flatMap(list)) if (named(p)) allowed.add(named(p));
  // In a message, the focus nodes of a shape are what it allows of a
  // subject: an IRI or a blank node.
  const focusOf = (nodes) => {
    const terms = nodes.flatMap((node) => valueTerms(node, false));
    return !terms.length || terms.some((term) => term instanceof Var) ? [new Struct('iri', [any()]), new Struct('bnode', [any(), any()])] : terms;
  };
  for (const [id, stated] of about) {
    const pathNode = value(stated[0][0], SH + 'path');
    if (pathNode === undefined) continue;
    const { predicates, direct, inverse } = path(pathNode);
    const focus = input ? focusOf(owners.get(id) ?? []) : [any()];
    for (const predicate of predicates) {
      allowed.add(predicate);
      const p = new Struct('iri', [predicate]);
      const objects = direct || inverse ? valueTerms(stated[0][0], !input || predicate === RDF + 'type') : [any()];
      for (const subject of focus) {
        for (const object of objects) {
          const [s, o] = [subject, object].map((term) => freshTerm(term, `s${++fresh}`));
          // Shapes describe a message's triples, which are in its default
          // graph; an output contract asks for them in any graph.
          const g = input ? 'default_graph' : any();
          patterns.push(new Struct('rdf', inverse ? [o, p, s, g] : [s, p, o, g]));
        }
      }
    }
  }
  if (!patterns.length) throw new EyemindError(`${name}: the SHACL shapes describe no triples`);
  return { patterns, allowed: closed ? allowed : null };
}
let fresh = 0;

// The patterns of triples messages have, from a SHACL input shape. When the
// shapes are closed, a message triple of another property is dropped.
export const shaclIn = (quads, name) => shapePatterns(quads, name, true);
// An output contract from SHACL output shapes: their property shapes'
// triples, of the values they allow.
export const shaclOut = (quads, name) => shapePatterns(quads, name, false).patterns;

const RDF_TYPE = RDF + 'type';
const RDFS = 'http://www.w3.org/2000/01/rdf-schema#', OWL = 'http://www.w3.org/2002/07/owl#';
// Schema properties and property types whose rules can only fire when the
// background has them.
const SCHEMA = new Set([...['domain', 'range', 'subClassOf', 'subPropertyOf'].map((n) => RDFS + n),
  ...['equivalentClass', 'equivalentProperty', 'inverseOf', 'propertyChainAxiom', 'intersectionOf', 'unionOf', 'oneOf',
    'members', 'distinctMembers', 'hasKey', 'onProperty', 'onClass', 'onDataRange', 'someValuesFrom', 'allValuesFrom',
    'hasValue', 'maxCardinality', 'maxQualifiedCardinality', 'complementOf', 'disjointWith', 'disjointUnionOf',
    'datatypeComplementOf'].map((n) => OWL + n)]);
const TYPE_GUARDS = new Set(['FunctionalProperty', 'InverseFunctionalProperty', 'TransitiveProperty', 'SymmetricProperty',
  'AsymmetricProperty', 'IrreflexiveProperty', 'ReflexiveProperty', 'AllDifferent', 'AllDisjointClasses',
  'AllDisjointProperties'].map((n) => OWL + n));
const QUADS = new Set(['rdf/4', 'ent_base/4']);

// The rules for messages that trusted SHACL shapes plan, at the level of
// properties and classes: a rule whose schema premise the background lacks
// is left out; with input shapes, only rules whose premises can match a
// property or class of the background, the messages or a kept rule's
// conclusion are kept; with output shapes, only rules concluding a property
// or class asked for, or one a kept rule reads. A relation other than a
// triple counts as a property of its own. Facts and backward rules stay.
export function planRules(program, quads, { input = null, output = null }) {
  const named = (t) => t instanceof Struct && t.name === 'iri' && typeof t.args[0] === 'string' ? t.args[0] : null;
  const describe = (goals, into) => {
    for (const goal of goals) {
      if (!(goal instanceof Struct)) continue;
      const k = key(goal);
      if (CONTROL_KEYS.has(k)) { describe(goal.args, into); continue; }
      if (!QUADS.has(k)) { into.predicates.add('#' + k); continue; }
      const p = named(goal.args[1]);
      if (p === null) { into.variable = true; continue; }
      if (p === RDF_TYPE && named(goal.args[2])) into.classes.add(named(goal.args[2]));
      else into.predicates.add(p);
    }
    return into;
  };
  const entry = () => ({ predicates: new Set(), classes: new Set(), variable: false });
  // The values a variable takes in a schema premise, such as P2 in
  // rdf(P1, rdfs:subPropertyOf, P2), from the background's triples of that
  // property, as partial evaluation makes them; null for no such premise.
  const values = (variable, body) => {
    for (const goal of body) {
      if (!(goal instanceof Struct) || !QUADS.has(key(goal))) continue;
      const p = named(goal.args[1]);
      const at = [0, 2].find((i) => goal.args[i] instanceof Var && goal.args[i].name === variable.name);
      if (p === null || p === RDF_TYPE || at === undefined) continue;
      return [...new Set(quads.filter((quad) => named(quad[1]) === p).map((quad) => named(quad[at])).filter(Boolean))];
    }
    return null;
  };
  // The properties and classes of goals, a variable one taking its values.
  const partial = (goals, body) => {
    const into = entry();
    for (const goal of goals) {
      if (!(goal instanceof Struct) || !QUADS.has(key(goal))) { describe([goal], into); continue; }
      const [, p, o] = goal.args;
      if (p instanceof Var) {
        const found = values(p, body);
        if (found === null) into.variable = true;
        else for (const value of found) into.predicates.add(value);
      } else if (named(p) === RDF_TYPE && o instanceof Var) {
        const found = values(o, body);
        if (found === null) into.predicates.add(RDF_TYPE);
        else for (const value of found) into.classes.add(value);
      } else describe([goal], into);
    }
    return into;
  };
  const rules = program.clauses.filter((c) => c.forward).map((clause) => ({ clause,
    body: partial(clause.body, clause.body), head: partial(clause.heads, clause.body) }));
  // What the background has, and what statically relevant rules conclude
  // from it.
  const known = entry();
  for (const quad of quads) {
    const p = named(quad[1]);
    if (p === RDF_TYPE && named(quad[2])) known.classes.add(named(quad[2]));
    else if (p) known.predicates.add(p);
  }
  for (const clause of program.clauses) if (!clause.forward && !clause.body.length) known.predicates.add('#' + key(clause.head));
  const matches = (body, have) => (!body.predicates.size && !body.classes.size) ||
    [...body.predicates].some((p) => have.predicates.has(p)) || [...body.classes].some((c) => have.classes.has(c));
  const close = (selected, have) => {
    const kept = new Set();
    for (let changed = true; changed;) {
      changed = false;
      for (const rule of selected) {
        if (kept.has(rule) || !matches(rule.body, have)) continue;
        kept.add(rule);
        for (const p of rule.head.predicates) have.predicates.add(p);
        for (const c of rule.head.classes) have.classes.add(c);
        changed = true;
      }
    }
    return kept;
  };
  const staticReach = close(rules, { predicates: new Set(known.predicates), classes: new Set(known.classes) });
  const background = { predicates: new Set(known.predicates), classes: new Set(known.classes) };
  for (const rule of staticReach) {
    for (const p of rule.head.predicates) background.predicates.add(p);
    for (const c of rule.head.classes) background.classes.add(c);
  }
  let selected = rules.filter((rule) => [...rule.body.predicates].every((p) => !SCHEMA.has(p) || background.predicates.has(p)) &&
    [...rule.body.classes].every((c) => !TYPE_GUARDS.has(c) || background.classes.has(c)));
  if (input) {
    const reached = close(selected, { predicates: new Set([...background.predicates, ...input.predicates]),
      classes: new Set([...background.classes, ...input.classes]) });
    selected = selected.filter((rule) => reached.has(rule));
  }
  if (output && !output.variable) {
    const desired = { predicates: new Set(output.predicates), classes: new Set(output.classes) };
    const needed = new Set();
    const wanted = (head) => {
      const anyClass = desired.predicates.has(RDF_TYPE);
      return (head.variable && desired.predicates.size && (!desired.classes.size || anyClass)) ||
        [...head.predicates].some((p) => desired.predicates.has(p)) ||
        [...head.classes].some((c) => anyClass || desired.classes.has(c));
    };
    for (let changed = true; changed;) {
      changed = false;
      for (const rule of selected) {
        if (needed.has(rule) || !wanted(rule.head)) continue;
        needed.add(rule);
        for (const p of rule.body.predicates) desired.predicates.add(p);
        for (const c of rule.body.classes) desired.classes.add(c);
        changed = true;
      }
    }
    selected = selected.filter((rule) => needed.has(rule));
  }
  const keep = new Set(selected.map((rule) => rule.clause.id));
  return new Program(program.sources.filter((_, i) => !program.byId.get(i + 1)?.forward || keep.has(i + 1)));
}

// The properties and classes of triple patterns.
const vocabularyOf = (patterns) => {
  const into = { predicates: new Set(), classes: new Set(), variable: false };
  for (const pattern of patterns) {
    const p = pattern.args[1]?.name === 'iri' ? pattern.args[1].args[0] : undefined;
    if (p === RDF_TYPE && pattern.args[2]?.name === 'iri' && typeof pattern.args[2].args[0] === 'string') into.classes.add(pattern.args[2].args[0]);
    else if (typeof p === 'string') into.predicates.add(p);
    else into.variable = true;
  }
  return into;
};

// Reasoning over messages one at a time, each with the same background
// graph: infer(quads) gives the triples a message adds to what the background
// alone concludes. The background is closed once and the rules are
// specialized to the kinds of triples a message has (specialize.js); a
// program that cannot be specialized runs whole for every message instead.
// With an output contract, only the rules that can contribute to its
// patterns are specialized, and only triples matching one are written.
// expected, from SHACL input shapes, has the patterns of message triples
// and, for closed shapes, the properties a kept triple has: the program for
// conforming messages is made before the first one arrives, and a message
// that does not conform gets one of its own shape.
export function messageReasoner({ quads, prefixes, wanted = null, expected = null, planned = false }, { profiles, source = '<input>', limits = {} }) {
  const options = { profiles, source };
  const whole = { ...options, stableRuleIds: true };
  // QUDT adds catalog facts during compilation from the units and metadata
  // in the current message. Run that compiler on each combined graph.
  const qudt = profiles.includes('qudt'), usePlan = planned && !qudt;
  const background = compileRdfLogic({ quads, prefixes }, qudt ? whole : { ...options, stream: true });
  // Trusted SHACL shapes plan the rules first, as rdfjs-inference-engine does.
  const program = usePlan ? planRules(background.program, quads, { input: expected && vocabularyOf(expected.patterns),
    output: wanted && vocabularyOf(wanted) }) : background.program;
  const specializer = qudt ? null : new Specializer(program, { quads: ['rdf/4', 'ent_base/4'], limits,
    wanted: wanted && wanted.flatMap((pattern) => [pattern, new Struct('ent_report', pattern.args)]) });
  // The program for the messages an input shape describes is made at once.
  if (expected) specializer?.expect(expected.patterns.flatMap((pattern) => [pattern, new Struct('ent_base', pattern.args)]));
  let serial = 0;
  const matches = (quad, patterns) => patterns.some((pattern) => unify(new Struct('rdf', quad), freshTerm(pattern, `w${++serial}`), new Env()));
  const kept = (quad) => wanted === null || matches(quad, wanted);
  let alone = null;
  const answers = (program, limits) => run(program, limits).conclusions.filter((t) => t instanceof Struct && t.name === 'result_rdf');
  return {
    prefixes: background.prefixes,
    reason: qudt ? 'QUDT resolves units from each message' : specializer.reason,
    specializer,
    // limits are run()'s bounds. The result has the added quads, whether
    // the rules were specialized, and the specialized program's sources the
    // first time a message has its shape; with input shapes, how many
    // triples were dropped and whether the rest conform.
    infer(message, runLimits = limits) {
      const all = message;
      if (expected?.allowed) message = message.filter((quad) => quad[1].name === 'iri' && expected.allowed.has(quad[1].args[0]));
      const shaped = expected ? { dropped: all.length - message.length } : {};
      const facts = message.flatMap((q) => [new Struct('rdf', q), new Struct('ent_base', q)]);
      const special = specializer?.specialize(facts) ?? null;
      if (special !== null) {
        const result = run(special.program, runLimits);
        const added = result.derived.map((node) => node.goal).filter((t) => !special.old.has(identity(t)) &&
          (t.name === 'ent_report' || (t.name === 'rdf' && RESOURCES.has(t.args[0].name) && t.args[1].name === 'iri')));
        return { quads: added.map((t) => t.args).filter(kept), specialized: true, stats: result.stats, haltCode: result.haltCode,
          sources: special.fresh ? special.sources : null, ...(expected ? { ...shaped, conforms: special.conforms } : {}) };
      }
      if (expected) shaped.conforms = message.every((quad) => matches(quad, expected.patterns));
      if (usePlan) {
        // The planned rules run whole over the background and the message.
        alone ??= new Set(run(program, runLimits).derived.map((node) => identity(node.goal)));
        const result = run(program.withFacts(facts), runLimits);
        const added = result.derived.map((node) => node.goal).filter((t) => !alone.has(identity(t)) &&
          (t.name === 'ent_report' || (t.name === 'rdf' && RESOURCES.has(t.args[0].name) && t.args[1].name === 'iri')));
        return { quads: added.map((t) => t.args).filter(kept), specialized: false, stats: result.stats, haltCode: result.haltCode, sources: null, ...shaped };
      }
      alone ??= new Set(answers(qudt ? background.program : compileRdfLogic({ quads, prefixes }, whole).program, runLimits).map(identity));
      const result = run(compileRdfLogic({ quads: [...quads, ...message], prefixes, shapes: quads }, whole).program, runLimits);
      const added = result.conclusions.filter((t) => t instanceof Struct && t.name === 'result_rdf' && !alone.has(identity(t)));
      return { quads: added.map((t) => t.args).filter(kept), specialized: false, stats: result.stats, haltCode: result.haltCode, sources: null, ...shaped };
    },
  };
}

// The subjects ent_resource/1 accepts.
const RESOURCES = new Set(['iri', 'bnode', 'skolem', 'triple']);

const COMMON = String.raw`
implied_by(ent_resource(iri(A)), is_atom(A));
implied_by(ent_resource(bnode(A, B)), [is_atom(A), is_atom(B)]);
implied_by(ent_resource(skolem(A, B, C)), 'true');
implied_by(ent_resource(triple(A, B, C)), 'true');
implies(rdf(S, P, O, G), ent_graph(G));
implies(rdf(S, P, O, G), [ent_node(S, G), ent_node(P, G), ent_node(O, G)]);
fact(ent_count([], 0));
implied_by(ent_count([_, ...T], N), [ent_count(T, M), is(N, add(M, 1))]);
fact(ent_member(X, [X, ..._]));
implied_by(ent_member(X, [_, ...T]), ent_member(X, T));
`;

const REPORTS = String.raw`
// A report cannot create more ontology consequences or affect a constraint.
implies(ent_conflict(R, X, P, Y, G), [
  ent_report(B, iri('http://www.w3.org/1999/02/22-rdf-syntax-ns#type'), iri('https://eyereasoner.github.io/eyemind/entailment#Conflict'), G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#rule'), literal(R, datatype('http://www.w3.org/2001/XMLSchema#string')), G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#focus'), X, G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#left'), P, G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#right'), Y, G)
]);
`;

// The result restricted to an output contract: one query per pattern.
