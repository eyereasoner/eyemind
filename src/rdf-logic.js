// Explicit RDF profiles share one working graph. Validation and reports never
// feed back into it; LS stratification closes inference before validation.
import { loadText } from './lang.js';
import { rdfDocument } from './rdf.js';
import { write } from './writer.js';
import { owl2rlRules } from './owl2rl.js';
import { skosRules } from './skos.js';
import { qudtRules } from './qudt.js';
import { compileShacl } from './shacl.js';
import { rdfValueRules } from './rdf-values.js';

export const ENTAILMENT = 'https://eyereasoner.github.io/eyemind/entailment#';
export const RDF_PROFILES = ['owl2rl', 'qudt', 'skos', 'shacl'];

export function compileRdfLogic({ quads, prefixes }, { profiles, source = '<input>' }) {
  quads = [...new Map(quads.map((q) => [q.map((t) => write(t)).join(' '), q])).values()];
  const selected = new Set(profiles);
  const text = `// Generated by eyemind from ${String(source).replace(/[\r\n\u2028\u2029]/g, ' ')}, with ${profiles.map((p) => '--' + p).join(' ')}.\n` +
    '// rdf(S, P, O, G) is the working graph; result_rdf contains conclusions and reports.\n' +
    `facts_from({ text: ${JSON.stringify(rdfDocument(quads))} })\n` +
    `facts_from({ text: ${JSON.stringify(rdfDocument(quads, 'ent_base'))} })\n` + COMMON +
    (quads.length ? '' : "fact(ent_graph('default_graph'));\n") +
    (profiles.some((p) => p !== 'skos') ? rdfValueRules : '') +
    (selected.has('owl2rl') ? owl2rlRules : '') +
    (selected.has('skos') ? skosRules : '') +
    (selected.has('qudt') ? qudtRules : '') +
    (selected.has('shacl') ? compileShacl(quads) : '') + OUTPUT;
  return { kind: profiles[0], text, program: loadText(text, source),
    prefixes: { ...prefixes, ent: ENTAILMENT, ...(selected.has('skos') ? { skos: 'http://www.w3.org/2004/02/skos/core#' } : {}),
      ...(selected.has('qudt') ? { qconv: 'https://eyereasoner.github.io/eyemind/qudt#', qudt: 'http://qudt.org/schema/qudt/', unit: 'http://qudt.org/vocab/unit/' } : {}),
      ...(selected.has('shacl') ? { sh: 'http://www.w3.org/ns/shacl#' } : {}) }, compiled: null };
}

const COMMON = String.raw`
implied_by(ent_resource(iri(A)), is_atom(A));
implied_by(ent_resource(bnode(A, B)), [is_atom(A), is_atom(B)]);
implied_by(ent_resource(skolem(A, B, C)), 'true');
implied_by(ent_resource(triple(A, B, C)), 'true');
implies(rdf(S, P, O, G), ent_graph(G));
implies(rdf(S, P, O, G), [ent_node(S, G), ent_node(P, G), ent_node(O, G)]);
fact(ent_count([], 0));
implied_by(ent_count([_, ...T], N), [ent_count(T, M), is(N, add(M, 1))]);
fact(ent_member(X, [X, ..._]));
implied_by(ent_member(X, [_, ...T]), ent_member(X, T));
`;

const OUTPUT = String.raw`
// A report cannot create more ontology consequences or affect a constraint.
implies(ent_conflict(R, X, P, Y, G), [
  ent_report(B, iri('http://www.w3.org/1999/02/22-rdf-syntax-ns#type'), iri('https://eyereasoner.github.io/eyemind/entailment#Conflict'), G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#rule'), literal(R, datatype('http://www.w3.org/2001/XMLSchema#string')), G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#focus'), X, G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#left'), P, G),
  ent_report(B, iri('https://eyereasoner.github.io/eyemind/entailment#right'), Y, G)
]);
implies([rdf(S, iri(P), O, G), ent_resource(S), not(ent_base(S, iri(P), O, G))], result_rdf(S, iri(P), O, G));
implies(ent_report(S, P, O, G), result_rdf(S, P, O, G));
query(result_rdf(S, P, O, G));
`;
